#!/bin/bash

declare -a paths=()
declare -a deps_list=()
declare -a codes=()

current_path=""
current_deps=""

# Parse -rule[:dep1:dep2] -subrule[:dep] "bash code"
while (( $# > 0 )); do
    if [[ "$1" == -* ]]; then
        token="${1#-}"

        # Split on first ':' if dependencies are present
        if [[ "$token" == *:* ]]; then
            rule_name="${token%%:*}"
            deps="${token#*:}"
            # Convert ':' separators into spaces (e.g., "a:b" -> "a b")
            deps="${deps//:/ }"
            current_deps="${current_deps:+$current_deps }$deps"
        else
            rule_name="$token"
        fi

        current_path="${current_path:+$current_path }$rule_name"
        shift
    else
        if [[ -z "$current_path" ]]; then
            echo "Error: code block '$1' given without a preceding -rule" >&2
            exit 1
        fi
        paths+=("$current_path")
        deps_list+=("$current_deps")
        codes+=("$1")
        current_path=""
        current_deps=""
        shift
    fi
done

if [[ -n "$current_path" ]]; then
    echo "Error: trailing rule '-$current_path' is missing its bash code block" >&2
    exit 1
fi

# Helper to turn a rule path like "build debug" into a valid function name "_rule_build__debug"
to_func_name() {
    local name="$1"
    name="${name// /__}"
    name="${name//-/_}"
    printf '_rule_%s' "$name"
}

# Emit generated script header + dependency runner
cat <<'EOF'
#!/usr/bin/env bash

# What follows was generated by jca.sh
# Edit at your discretion

if [ -n "$ZSH_VERSION" ] || [ "${BASH_VERSINFO:-0}" -lt 4 ]; then
    echo "$SHELL is not supported, update bash (the real deal)" >&2
    exit 1
fi

set -e

declare -A _RAN_RULES=()

_run_rule() {
    local fn="$1"
    # Skip if already executed in this run (prevents diamond-dependency duplicates & infinite loops)
    [[ -n "${_RAN_RULES[$fn]}" ]] && return 0
    _RAN_RULES["$fn"]=1
    "$fn"
}

# Usage: jca_expect <expected_rc> <expected_stdout> <cmd...>
jca_expect() {
    local exp_rc="$1" exp_raw="$2"; shift 2
    local exp_out act_out act_rc=0
    exp_out="$(printf '%b' "$exp_raw"; printf x)"
    exp_out="${exp_out%x}"

    act_out="$("$@"; printf x)" || act_rc=$?
    act_out="${act_out%x}"

    if [[ "$act_rc" -ne "$exp_rc" ]]; then
        printf 'FAIL [%s]: expected rc %s, got %s\n' "$*" "$exp_rc" "$act_rc" >&2
        return 1
    fi
    if [[ "$act_out" != "$exp_out" ]]; then
        printf 'FAIL [%s]: stdout mismatch\n--- Expected ---\n%s\n--- Got ---\n%s\n' "$*" "$exp_out" "$act_out" >&2
        return 1
    fi
    echo "PASS: $*"
}

# Usage: jca_expect_in <stdin_str> <expected_rc> <expected_stdout> <cmd...>
jca_expect_in() {
    local in_str="$1" exp_rc="$2" exp_raw="$3"; shift 3
    local exp_out act_out act_rc=0
    exp_out="$(printf '%b' "$exp_raw"; printf x)"
    exp_out="${exp_out%x}"

    act_out="$(printf '%b' "$in_str" | "$@"; printf x)" || act_rc=$?
    act_out="${act_out%x}"

    if [[ "$act_rc" -ne "$exp_rc" ]]; then
        printf 'FAIL [%s]: expected rc %s, got %s\n' "$*" "$exp_rc" "$act_rc" >&2
        return 1
    fi
    if [[ "$act_out" != "$exp_out" ]]; then
        printf 'FAIL [%s]: stdout mismatch\n--- Expected ---\n%s\n--- Got ---\n%s\n' "$*" "$exp_out" "$act_out" >&2
        return 1
    fi
    echo "PASS: $*"
}

# Usage: jca_fuzz <iterations> <timeout_duration> <cmd...>
jca_fuzz() {
    local iters="$1" tout="$2"; shift 2
    local i rc
    for (( i=1; i<=iters; i++ )); do
        rc=0
        head -c 512 /dev/urandom | timeout "$tout" "$@" >/dev/null 2>&1 || rc=$?
        if [[ "$rc" -ge 128 || "$rc" -eq 124 ]]; then
            printf 'FUZZ FAIL [%s]: crash/hang (rc=%s) at iteration %s\n' "$*" "$rc" "$i" >&2
            return 1
        fi
    done
}

# Usage:
#   if jca_newer main main.c; then gcc ...; fi
#   OR: jca_newer main main.c -- gcc -Wall ... main.c -o main
jca_newer() {
    local target="$1"; shift
    local srcs=()
    while (( $# > 0 )) && [[ "$1" != "--" ]]; do
        srcs+=("$1"); shift
    done
    local has_cmd=0
    if [[ "$1" == "--" ]]; then
        has_cmd=1; shift
    fi

    local dirty=0
    if [[ ! -e "$target" ]]; then
        dirty=1
    else
        local src
        for src in "${srcs[@]}"; do
            [[ "$src" -nt "$target" ]] && { dirty=1; break; }
        done
    fi

    if (( has_cmd )); then
        (( dirty )) && "$@"
        return 0
    fi
    (( dirty ))
}

# Usage: jca_env [.env]
jca_env() {
    local env_file="${1:-.env}"
    if [[ ! -f "$env_file" ]]; then
        echo "Error: env file '$env_file' not found" >&2
        return 1
    fi
    local line
    while IFS= read -r line || [[ -n "$line" ]]; do
        [[ -z "$line" || "$line" =~ ^[[:space:]]*# ]] && continue
        if [[ "$line" =~ ^[[:space:]]*([A-Za-z_][A-Za-z0-9_]*)=(.*)$ ]]; then
            local key="${BASH_REMATCH[ 1 ]}" val="${BASH_REMATCH[ 2 ]}"
            val="${val%\"}" ; val="${val#\"}"
            val="${val%\'}" ; val="${val#\'}"
            export "$key=$val"
        fi
    done < "$env_file"
}

# Usage: jca_synth <max_iters> <model> <target_file> <verify_cmd>
# Example: jca_synth 10 "ollama/qwen2.5-coder:32b" app.py "./$TGT test"
jca_synth() {
    local iters="$1" model="$2" target="$3"; shift 3
    local verify_cmd="$*"

    local url="${OPENAI_BASE_URL:-https://api.deepseek.com}/v1/chat/completions"
    local key="${DEEPSEEK_API_KEY:-${OPENAI_API_KEY:-ollama}}"
    if [[ "$model" == ollama/* ]]; then
        url="${OLLAMA_HOST:-http://localhost:11434}/v1/chat/completions"
        model="${model#ollama/}"
        key="ollama"
    fi

    _jca_json_esc() {
        local s="$1"
        s="${s//\\/\\\\}"; s="${s//\"/\\\"}"
        s="${s//$'\n'/\\n}"; s="${s//$'\r'/\\r}"; s="${s//$'\t'/\\t}"
        printf '"%s"' "$s"
    }

    local i err="" rc=0
    for (( i=1; i<=iters; i++ )); do
        rc=0
        err="$(bash -c "$verify_cmd" 2>&1)" || rc=$?
        if [[ "$rc" -eq 0 ]]; then
            echo "[jca_synth] Adheres to spec (pass $i/$iters)."
            return 0
        fi

        echo "[jca_synth] Pass $i/$iters failed -> patching $target via $model..."
        local cur=""; [[ -f "$target" ]] && cur="$(cat "$target")"
        local prompt="Modify ${target} so that the verification command succeeds.

Current contents of ${target}:
${cur}

Verification command: ${verify_cmd}
Failure output:
${err}

Output ONLY the complete updated contents of ${target}. No markdown fences, no commentary."

        local payload resp
        payload=$(printf '{"model":%s,"temperature":0.2,"messages":[{"role":"user","content":%s}]}' \
            "$(_jca_json_esc "$model")" "$(_jca_json_esc "$prompt")")

        resp="$(curl -sS -X POST "$url" \
            -H "Content-Type: application/json" \
            -H "Authorization: Bearer ${key}" \
            -d "$payload")"

        python3 -c '
import sys, json, re
d = json.load(sys.stdin)
if "error" in d:
    sys.stderr.write(f"API Error: " + str(d["error"]) + "\n")
    sys.exit(1)
t = d["choices"][ 0 ]["message"]["content"]
m = re.search(r"```[a-zA-Z0-9_-]*\s*\n(.*?)```", t, re.DOTALL)
print(m.group(1).strip() if m else t.strip())
' <<< "$resp" > "$target"
    done

    echo "[jca_synth] Failed after $iters passes. Last error:" >&2
    echo "$err" >&2
    return 1
}

EOF

# Emit a Bash function for each rule
for i in "${!paths[@]}"; do
    fn_name="$(to_func_name "${paths[$i]}")"
    printf '%s() {\n' "$fn_name"

    # Call each dependency first
    for dep in ${deps_list[$i]}; do
        # Allow dots or slashes in dependency syntax to map to subrules (e.g., "build.clean" -> "build clean")
        dep_path="${dep//./ }"
        dep_fn="$(to_func_name "$dep_path")"
        printf '    _run_rule %s\n' "$dep_fn"
    done

    # Emit the rule's own bash code
    printf '    %s\n' "$(printf '%s' "${codes[$i]}" | envsubst)"
    printf '}\n\n'
done

# Emit the main CLI dispatcher
cat <<'EOF'
case "$*" in
EOF

for i in "${!paths[@]}"; do
    fn_name="$(to_func_name "${paths[$i]}")"
    printf '    %q)\n' "${paths[$i]}"
    printf '        _run_rule %s\n' "$fn_name"
    printf '        ;;\n'
done

cat <<'EOF'
    "")
        echo "No rule provided" >&2
        exit 1
        ;;
    *)
        echo "Unknown rule: $*" >&2
        exit 1
        ;;
esac
EOF
