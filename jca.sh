#!/bin/bash

declare -a paths=()
declare -a deps_list=()
declare -a codes=()

current_path=""
current_deps=""

# Parse -rule[:dep1:dep2] -subrule[:dep] "bash code"
while (( $# > 0 )); do
    if [[ "$1" == -* ]]; then
        token="${1#-}"
        
        # Split on first ':' if dependencies are present
        if [[ "$token" == *:* ]]; then
            rule_name="${token%%:*}"
            deps="${token#*:}"
            # Convert ':' separators into spaces (e.g., "a:b" -> "a b")
            deps="${deps//:/ }"
            current_deps="${current_deps:+$current_deps }$deps"
        else
            rule_name="$token"
        fi

        current_path="${current_path:+$current_path }$rule_name"
        shift
    else
        if [[ -z "$current_path" ]]; then
            echo "Error: code block '$1' given without a preceding -rule" >&2
            exit 1
        fi
        paths+=("$current_path")
        deps_list+=("$current_deps")
        codes+=("$1")
        current_path=""
        current_deps=""
        shift
    fi
done

if [[ -n "$current_path" ]]; then
    echo "Error: trailing rule '-$current_path' is missing its bash code block" >&2
    exit 1
fi

# Helper to turn a rule path like "build debug" into a valid function name "_rule_build__debug"
to_func_name() {
    local name="$1"
    name="${name// /__}"
    name="${name//-/_}"
    printf '_rule_%s' "$name"
}

# Emit generated script header + dependency runner
cat <<'EOF'
#!/usr/bin/env bash

# What follows was generated by jca.sh
# Edit at your discretion

set -e

declare -A _RAN_RULES=()

_run_rule() {
    local fn="$1"
    # Skip if already executed in this run (prevents diamond-dependency duplicates & infinite loops)
    [[ -n "${_RAN_RULES[$fn]}" ]] && return 0
    _RAN_RULES["$fn"]=1
    "$fn"
}

# Usage: jca_expect <expected_rc> <expected_stdout> <cmd...>
jca_expect() {
    local exp_rc="$1" exp_raw="$2"; shift 2
    local exp_out act_out act_rc=0
    exp_out="$(printf '%b' "$exp_raw"; printf x)"
    exp_out="${exp_out%x}"

    act_out="$("$@"; printf x)" || act_rc=$?
    act_out="${act_out%x}"

    if [[ "$act_rc" -ne "$exp_rc" ]]; then
        printf 'FAIL [%s]: expected rc %s, got %s\n' "$*" "$exp_rc" "$act_rc" >&2
        return 1
    fi
    if [[ "$act_out" != "$exp_out" ]]; then
        printf 'FAIL [%s]: stdout mismatch\n--- Expected ---\n%s\n--- Got ---\n%s\n' "$*" "$exp_out" "$act_out" >&2
        return 1
    fi
    echo "PASS: $*"
}


# Usage: jca_expect_in <stdin_str> <expected_rc> <expected_stdout> <cmd...>
jca_expect_in() {
    local in_str="$1" exp_rc="$2" exp_out="$3"; shift 3
    local act_out act_rc=0
    act_out="$(printf '%s' "$in_str" | "$@")" || act_rc=$?
    if [[ "$act_rc" -ne "$exp_rc" ]]; then
        printf 'FAIL [%s]: expected rc %s, got %s\n' "$*" "$exp_rc" "$act_rc" >&2
        return 1
    fi
    if [[ "$act_out" != "$exp_out" ]]; then
        printf 'FAIL [%s]: stdout mismatch\n--- Expected ---\n%s\n--- Got ---\n%s\n' "$*" "$exp_out" "$act_out" >&2
        return 1
    fi
}

# Usage: jca_fuzz <iterations> <timeout_duration> <cmd...>
jca_fuzz() {
    local iters="$1" tout="$2"; shift 2
    local i rc
    for (( i=1; i<=iters; i++ )); do
        rc=0
        head -c 512 /dev/urandom | timeout "$tout" "$@" >/dev/null 2>&1 || rc=$?
        if [[ "$rc" -ge 128 || "$rc" -eq 124 ]]; then
            printf 'FUZZ FAIL [%s]: crash/hang (rc=%s) at iteration %s\n' "$*" "$rc" "$i" >&2
            return 1
        fi
    done
}

# Usage:
#   if jca_newer main main.c; then gcc ...; fi
#   OR: jca_newer main main.c -- gcc -Wall ... main.c -o main
jca_newer() {
    local target="$1"; shift
    local srcs=()
    while (( $# > 0 )) && [[ "$1" != "--" ]]; do
        srcs+=("$1"); shift
    done
    local has_cmd=0
    if [[ "$1" == "--" ]]; then
        has_cmd=1; shift
    fi

    local dirty=0
    if [[ ! -e "$target" ]]; then
        dirty=1
    else
        local src
        for src in "${srcs[@]}"; do
            [[ "$src" -nt "$target" ]] && { dirty=1; break; }
        done
    fi

    if (( has_cmd )); then
        (( dirty )) && "$@"
        return 0
    fi
    (( dirty ))
}

EOF

# Emit a Bash function for each rule
for i in "${!paths[@]}"; do
    fn_name="$(to_func_name "${paths[$i]}")"
    printf '%s() {\n' "$fn_name"

    # Call each dependency first
    for dep in ${deps_list[$i]}; do
        # Allow dots or slashes in dependency syntax to map to subrules (e.g., "build.clean" -> "build clean")
        dep_path="${dep//./ }"
        dep_fn="$(to_func_name "$dep_path")"
        printf '    _run_rule %s\n' "$dep_fn"
    done

    # Emit the rule's own bash code
    printf '    %s\n' "$(printf '%s' "${codes[$i]}" | envsubst)"
    printf '}\n\n'
done

# Emit the main CLI dispatcher
cat <<'EOF'
case "$*" in
EOF

for i in "${!paths[@]}"; do
    fn_name="$(to_func_name "${paths[$i]}")"
    printf '    %q)\n' "${paths[$i]}"
    printf '        _run_rule %s\n' "$fn_name"
    printf '        ;;\n'
done

cat <<'EOF'
    *)
        echo "Unknown rule: $*" >&2
        exit 1
        ;;
esac
EOF
